"""
Generates a .cube LUT file that encodes the Virals Cinematic Look.

This LUT can be loaded directly in DaVinci Resolve's Color tab (Nodes -> LUT),
giving full auditability and non-destructive control over the grading.

The look mirrors the FFmpeg filters previously used:
  - contrast=1.1, saturation=1.25, brightness=+0.02
  - Teal & Orange colorbalance (warm highlights, cool shadows)
  - Subtle sharpening (handled separately, not in LUT)
"""

import os
import logging

logger = logging.getLogger("virals-lut-generator")

LUT_SIZE = 33  # Industry standard for DaVinci Resolve


def _clamp(v: float) -> float:
    return max(0.0, min(1.0, v))


def _apply_virals_look(r: float, g: float, b: float):
    """
    Applies the Virals aesthetic transform to a single RGB triplet (0-1 range).
    """
    # 1. Brightness +0.02
    r += 0.02
    g += 0.02
    b += 0.02

    # 2. Contrast 1.1 (pivot at 0.5)
    contrast = 1.1
    r = (r - 0.5) * contrast + 0.5
    g = (g - 0.5) * contrast + 0.5
    b = (b - 0.5) * contrast + 0.5

    # 3. Saturation 1.25
    sat = 1.25
    luma = 0.2126 * r + 0.7152 * g + 0.0722 * b
    r = luma + sat * (r - luma)
    g = luma + sat * (g - luma)
    b = luma + sat * (b - luma)

    # 4. Teal & Orange color balance
    #    Highlights: rh=+0.04, gh=+0.02, bh=-0.02
    #    Shadows:    rs=-0.02, gs=0.00, bs=+0.04
    highlight_mask = luma  # brighter pixels get more highlight shift
    shadow_mask = 1.0 - luma  # darker pixels get more shadow shift

    r += 0.04 * highlight_mask + (-0.02) * shadow_mask
    g += 0.02 * highlight_mask + 0.00 * shadow_mask
    b += (-0.02) * highlight_mask + 0.04 * shadow_mask

    return _clamp(r), _clamp(g), _clamp(b)


def generate_virals_cube_lut(output_path: str, size: int = LUT_SIZE) -> str:
    """
    Generates a .cube LUT file encoding the Virals Cinematic Look.
    Compatible with DaVinci Resolve, Premiere Pro, Final Cut Pro.
    """
    logger.info(f"Generating Virals .cube LUT ({size}x{size}x{size}) -> {output_path}")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)

    with open(output_path, "w") as f:
        f.write("# Virals Cinematic Look - Teal & Orange\n")
        f.write("# Generated by Virals Industrial Pipeline\n")
        f.write(f"LUT_3D_SIZE {size}\n")
        f.write("DOMAIN_MIN 0.0 0.0 0.0\n")
        f.write("DOMAIN_MAX 1.0 1.0 1.0\n")
        f.write("\n")

        for b_i in range(size):
            for g_i in range(size):
                for r_i in range(size):
                    r_in = r_i / (size - 1)
                    g_in = g_i / (size - 1)
                    b_in = b_i / (size - 1)

                    r_out, g_out, b_out = _apply_virals_look(r_in, g_in, b_in)
                    f.write(f"{r_out:.6f} {g_out:.6f} {b_out:.6f}\n")

    logger.info(f"LUT generated successfully: {output_path}")
    return output_path


if __name__ == "__main__":
    logging.basicConfig(level=logging.INFO)
    generate_virals_cube_lut("squads/outputs/export-for-davinci/virals_cinematic.cube")
