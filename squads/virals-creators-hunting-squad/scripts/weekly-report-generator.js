const path = require('path');
const fs = require('fs');

const SQUAD_ROOT = path.join(__dirname, '..');
const DISCOVERIES_DIR = path.join(SQUAD_ROOT, 'data/discoveries');
const SCORECARDS_DIR = path.join(SQUAD_ROOT, 'data/scorecards');
const OUTREACH_DIR = path.join(SQUAD_ROOT, 'data/outreach');
const REPORTS_DIR = path.join(SQUAD_ROOT, 'data/reports');

if (!fs.existsSync(REPORTS_DIR)) fs.mkdirSync(REPORTS_DIR, { recursive: true });

function getWeekDates(weekNum) {
    const now = new Date();
    const start = new Date(now);
    start.setDate(start.getDate() - start.getDay() + 1); // Monday
    const end = new Date(start);
    end.setDate(end.getDate() + 6); // Sunday
    return { start, end };
}

function countFilesInRange(dir, startDate, endDate) {
    if (!fs.existsSync(dir)) return 0;
    return fs.readdirSync(dir).filter(f => {
        const dateMatch = f.match(/(\d{4}-\d{2}-\d{2})/);
        if (!dateMatch) return false;
        const fileDate = new Date(dateMatch[1]);
        return fileDate >= startDate && fileDate <= endDate;
    }).length;
}

function loadJsonFiles(dir, pattern) {
    if (!fs.existsSync(dir)) return [];
    return fs.readdirSync(dir)
        .filter(f => f.endsWith('.json') && (!pattern || f.includes(pattern)))
        .map(f => { try { return JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8')); } catch(e) { return null; } })
        .filter(Boolean);
}

function generateReport() {
    const { start, end } = getWeekDates();
    const weekNum = Math.ceil((new Date() - new Date(new Date().getFullYear(), 0, 1)) / (7 * 24 * 60 * 60 * 1000));
    
    // Collect metrics
    const discoveries = loadJsonFiles(DISCOVERIES_DIR);
    const totalDiscovered = discoveries.reduce((sum, d) => sum + (d.metadata?.total_discovered || d.creators?.length || 0), 0);
    
    const scorecardFiles = loadJsonFiles(SCORECARDS_DIR);
    let qualified = 0, monitor = 0, rejected = 0;
    scorecardFiles.forEach(sc => {
        if (sc.metadata) {
            qualified += sc.metadata.qualified || 0;
            monitor += sc.metadata.monitor || 0;
            rejected += sc.metadata.rejected || 0;
        }
    });
    
    const outreachFiles = loadJsonFiles(OUTREACH_DIR);
    const totalOutreach = outreachFiles.reduce((sum, o) => sum + (o.metadata?.total || o.scripts?.length || 0), 0);
    
    const report = `# Weekly Hunt Report — Semana ${weekNum}

**Período:** ${start.toLocaleDateString('pt-BR')} a ${end.toLocaleDateString('pt-BR')}
**Gerado em:** ${new Date().toLocaleString('pt-BR')}

---

## 📊 Dashboard

| Métrica | Resultado | Meta |
|:--------|:----------|:-----|
| Prospects descobertos | ${totalDiscovered} | 15/semana |
| Qualificados (Score > 7) | ${qualified} | 12/semana |
| Outreach preparados | ${totalOutreach} | — |
| Monitor (Score 5-7) | ${monitor} | — |
| Rejeitados | ${rejected} | — |

## 🔍 Pipeline

\`\`\`
Descobertas:    ${'█'.repeat(Math.min(totalDiscovered, 20))} ${totalDiscovered}
Qualificadas:   ${'█'.repeat(Math.min(qualified, 20))} ${qualified}
Outreach:       ${'█'.repeat(Math.min(totalOutreach, 20))} ${totalOutreach}
\`\`\`

## 📁 Source Files

- Discoveries: ${fs.existsSync(DISCOVERIES_DIR) ? fs.readdirSync(DISCOVERIES_DIR).length : 0} files
- Scorecards: ${fs.existsSync(SCORECARDS_DIR) ? fs.readdirSync(SCORECARDS_DIR).length : 0} files
- Outreach: ${fs.existsSync(OUTREACH_DIR) ? fs.readdirSync(OUTREACH_DIR).length : 0} files

---

_Generated by: @hunter-manager (Jason) — weekly-report-generator.js_
`;

    const dateStr = new Date().toISOString().split('T')[0];
    const outputFile = path.join(REPORTS_DIR, `weekly-report-${dateStr}.md`);
    fs.writeFileSync(outputFile, report);
    console.log(`📊 Weekly report generated: ${outputFile}`);
    console.log(report);
    return outputFile;
}

if (require.main === module) {
    generateReport();
}

module.exports = { generateReport };
