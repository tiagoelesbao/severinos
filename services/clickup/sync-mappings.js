const fs = require('fs');
const path = require('path');

/**
 * Script para sincronizar o mapping.js e clickup_hierarchy.json 
 * a partir do clickup_advanced_metadata.json.
 */

const METADATA_PATH = path.join(__dirname, 'clickup_advanced_metadata.json');
const HIERARCHY_PATH = path.join(__dirname, 'clickup_hierarchy.json');
const MAPPING_PATH = path.join(__dirname, 'mapping.js');

function sync() {
    console.log('🔄 Iniciando sincronização de arquivos de mapeamento...');

    if (!fs.existsSync(METADATA_PATH)) {
        console.error('❌ Erro: clickup_advanced_metadata.json não encontrado. Execute o refresh primeiro.');
        process.exit(1);
    }

    const metadata = JSON.parse(fs.readFileSync(METADATA_PATH, 'utf8'));
    const hierarchy = {};

    // 1. Construir Objeto de Hierarquia Simplificado
    for (const [spaceName, spaceData] of Object.entries(metadata.hierarchy)) {
        hierarchy[spaceName] = {
            id: spaceData.id,
            folders: {},
            folderless_lists: {}
        };

        for (const [folderName, folderData] of Object.entries(spaceData.folders)) {
            hierarchy[spaceName].folders[folderName] = {
                id: folderData.id,
                lists: {}
            };
            for (const [listName, listData] of Object.entries(folderData.lists)) {
                hierarchy[spaceName].folders[folderName].lists[listName] = listData.id;
            }
        }

        for (const [listName, listData] of Object.entries(spaceData.folderless_lists)) {
            hierarchy[spaceName].folderless_lists[listName] = listData.id;
        }
    }

    // 2. Salvar clickup_hierarchy.json
    fs.writeFileSync(HIERARCHY_PATH, JSON.stringify(hierarchy, null, 2));
    console.log('✅ clickup_hierarchy.json atualizado.');

    // 3. Gerar conteúdo para mapping.js
    const mappingContent = `/**
 * AUTO-GENERATED FILE - DO NOT EDIT MANUALLY
 * Generated by sync-mappings.js based on clickup_advanced_metadata.json
 */

const VIRALS_CLICKUP_MAPPING = ${JSON.stringify(hierarchy, null, 2)};

/**
 * Resolves a human-readable string path into a ClickUp List ID.
 */
function getListId(departmentName, areaName, processName) {
    const department = VIRALS_CLICKUP_MAPPING[departmentName];
    if (!department) throw new Error(\`Departamento '\${departmentName}' não encontrado no mapping. Options: \${Object.keys(VIRALS_CLICKUP_MAPPING)}\`);
    
    // Exact or loose match for areas
    const areaKey = Object.keys(department.folders).find(k => k.includes(areaName) || areaName.includes(k)) || 
                    Object.keys(department.folderless_lists).find(k => k.includes(areaName) || areaName.includes(k));
    
    if (!areaKey) throw new Error(\`Área '\${areaName}' não encontrada dentro de '\${departmentName}'.\`);

    const folder = department.folders[areaKey];
    if (folder) {
        const processKey = Object.keys(folder.lists).find(k => k.includes(processName) || processName.includes(k));
        const listId = folder.lists[processKey];
        if (!listId) throw new Error(\`Processo '\${processName}' não encontrado na pasta '\${areaKey}'.\`);
        return listId;
    }

    return department.folderless_lists[areaKey];
}

module.exports = {
    VIRALS_CLICKUP_MAPPING,
    getListId
};
`;

    fs.writeFileSync(MAPPING_PATH, mappingContent);
    console.log('✅ mapping.js atualizado e agora é auto-gerado.');
}

if (require.main === module) {
    sync();
}
